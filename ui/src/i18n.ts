import { useSyncExternalStore } from 'react';

/**
 * French and English. The language follows the system's until someone picks
 * one with the switch in the top bar; the choice is kept in this browser.
 *
 * French is written first and is the reference: English must have the same
 * keys (i18n.test.ts checks it, along with the copy rules: no em or en dashes,
 * no " - " used as a dash).
 */

export type Lang = 'fr' | 'en';
type Vars = Record<string, string | number>;
export type Entry = string | ((v: Vars) => string);

const STORAGE = 'anon:lang';

function detect(): Lang {
  try {
    const stored = localStorage.getItem(STORAGE);
    if (stored === 'fr' || stored === 'en') return stored;
  } catch {
    /* private mode */
  }
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const p of prefs) {
    if (p?.toLowerCase().startsWith('fr')) return 'fr';
    if (p?.toLowerCase().startsWith('en')) return 'en';
  }
  return 'fr';
}

let lang: Lang = detect();
const listeners = new Set<() => void>();
document.documentElement.lang = lang;

export function setLang(next: Lang) {
  lang = next;
  document.documentElement.lang = next;
  document.title = t('brand');
  try {
    localStorage.setItem(STORAGE, next);
  } catch {
    /* private mode */
  }
  listeners.forEach((l) => l());
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb);
      return () => listeners.delete(cb);
    },
    () => lang,
  );
}

